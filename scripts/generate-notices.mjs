import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
if (!process.env.npm_execpath) throw new Error('Run this script with npm run notices.');
const directories = execFileSync(process.execPath, [process.env.npm_execpath, 'ls', '--omit=dev', '--all', '--parseable'], { cwd: root, encoding: 'utf8' })
  .trim().split(/\r?\n/).filter(directory => resolve(directory) !== resolve(root));
const sections = [];
for (const directory of directories) {
  const metadata = JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8'));
  const files = readdirSync(directory, { withFileTypes: true })
    .filter(file => file.isFile() && /^(licen[cs]e|notice|copying|copyright)(\.|$)/i.test(file.name))
    .map(file => file.name).sort();
  let text = files.map(file => `${file}\n\n${readFileSync(join(directory, file), 'utf8').replace(/\r\n/g, '\n').trim()}`).join('\n\n');
  if (!text && metadata.name === 'react-remove-scroll-bar' && metadata.version === '2.3.8') {
    text = readFileSync(join(root, 'scripts/licenses/react-remove-scroll-bar-2.3.8.txt'), 'utf8').trim();
  }
  if (!text) throw new Error(`Missing license text for ${metadata.name}@${metadata.version}. Add the upstream notice before distributing.`);
  sections.push({ key: `${metadata.name}@${metadata.version}`, text: `License identifier: ${metadata.license ?? 'See license text'}\n\n${text}` });
}
for (const [name, file] of [['Space Grotesk (local font files)', 'OFL.txt'], ['DejaVu (local font files)', 'DejaVu-LICENSE.txt']]) {
  sections.push({ key: name, text: readFileSync(join(root, 'public/fonts', file), 'utf8').replace(/\r\n/g, '\n').trim() });
}
sections.sort((a, b) => a.key < b.key ? -1 : a.key > b.key ? 1 : 0);
const header = `FRAME — Third-party notices

Generated by npm run notices from installed production dependencies and bundled fonts.
These components retain their own licenses. This file is copied into the web build.
Development-only tooling is excluded; its licenses remain in the corresponding npm packages.
Some optional peer type definitions are included conservatively.
`;
writeFileSync(join(root, 'public/THIRD_PARTY_NOTICES.txt'), header + sections.map(section => `\n${'='.repeat(78)}\n${section.key}\n${'='.repeat(78)}\n\n${section.text}\n`).join(''));
writeFileSync(join(root, 'public/LICENSE.txt'), readFileSync(join(root, 'LICENSE'), 'utf8'));
console.log(`Wrote notices for ${directories.length} production packages and bundled Space Grotesk/DejaVu fonts.`);
